

USE ROLE ACCOUNTADMIN;


  CREATE OR REPLACE API INTEGRATION GIT_API_INT
  API_PROVIDER = GIT_HTTPS_API
  API_ALLOWED_PREFIXES = ('https://github.com/akhilgeda99')
  ALLOWED_AUTHENTICATION_SECRETS = (BLINKIT_DB.S3_SCHEMA.GIT_SECRET)  -- omit for public repos
  ENABLED = TRUE;

  CREATE OR REPLACE GIT REPOSITORY BLINKIT_DB.S3_SCHEMA.MY_REPO
  API_INTEGRATION = GIT_API_INT
  GIT_CREDENTIALS = BLINKIT_DB.S3_SCHEMA.GIT_SECRET   -- omit for public repos
  ORIGIN = 'https://github.com/akhilgeda99/snowflake.git';

  ALTER GIT REPOSITORY BLINKIT_DB.S3_SCHEMA.MY_REPO FETCH;

SHOW GIT BRANCHES IN GIT REPOSITORY BLINKIT_DB.S3_SCHEMA.MY_REPO;
LS @BLINKIT_DB.S3_SCHEMA.MY_REPO/branches/main/;

-- run a SQL script from the repo
EXECUTE IMMEDIATE FROM @BLINKIT_DB.S3_SCHEMA.MY_REPO/branches/main/scripts/setup.sql;